def source_label(chunk: Chunk) -> str:
    label = f"{chunk.law_name} — {chunk.chapter}"
    return f"{label} — มาตรา {chunk.section}" if chunk.section else label


def build_context(hits: list[Hit]) -> str:
    blocks, budget = [], MAX_CONTEXT_CHARS
    for n, h in enumerate(hits, 1):
        text = h.chunk.section_text
        limit = min(MAX_SECTION_CHARS, budget)
        if limit <= 0:
            break
        if len(text) > limit:
            text = text[:limit] + " …(ตัดทอน)"
        budget -= len(text)
        blocks.append(f"[{n}] {source_label(h.chunk)}\n{text}")
    return "<context>\n" + "\n\n".join(blocks) + "\n</context>"


_NOTE_LINE_RE = re.compile(r"^[\s*_]*หมายเหตุ[\s*_:：]*(.*)$")


def clean_answer(answer: str) -> str:
    """ตัดคำเตือนท้ายคำตอบที่ LLM พิมพ์ซ้ำ (บางครั้งวนจนหมดโทเคน) และบรรทัดซ้ำติดกัน
    แต่เก็บหมายเหตุที่เป็นเนื้อหา (อ้างมาตราหรือ [n]) ไว้"""
    out: list[str] = []
    for line in answer.strip().split("\n"):
        s = line.strip()
        note = _NOTE_LINE_RE.match(s)
        if note and not re.search(r"มาตรา|\[\d+\]", note.group(1)):
            continue
        if s and ("หมายเหตุ".startswith(s) or ("คำปรึกษา" in s and len(s) < 80)):
            continue
        if s and out and out[-1].strip() == s:
            continue
        out.append(line)
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()


def is_not_found(answer: str) -> bool:
    # LLM บางครั้งขึ้นต้นด้วย "ขออภัย" ก่อนประโยคปฏิเสธ จึงดูเฉพาะช่วงต้นของคำตอบ
    return "ไม่พบข้อมูล" in answer.strip()[:40]
